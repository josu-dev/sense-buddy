const dicts: Record<AppLang, Record<StringKey, string>> = { en, es };

/** Device language: Spanish if the phone is in Spanish, English otherwise. */
export function getDeviceLang(): AppLang {
  try {
    const code = getLocales()[0]?.languageCode ?? "en";
    return code.toLowerCase().startsWith("es") ? "es" : "en";
  } catch {
    return "en";
  }
}

/** Effective app language: manual preference, or phone language when unset/"system". */
export function getAppLang(): AppLang {
  return resolveLang(useBuddyStore.getState().prefs.language);
}

/** Effective app language: manual preference, or phone language when unset/"system". */
function resolveLang(pref: unknown): AppLang {
  if (pref === "es" || pref === "en") return pref;
  return getDeviceLang(); // covers "system" + stores persisted before this field existed
}

/** Current dictionary; re-renders the component when the preference changes. */
export function useStrings(): Record<StringKey, string> {
  const pref = useBuddyStore((s) => s.prefs.language);
  return dicts[resolveLang(pref)];
}
